export type ApiErrorCode = (typeof API_ERROR_CODES)[number];

const API_ERROR_CODE_SET: ReadonlySet<string> = new Set(API_ERROR_CODES);

export function isApiErrorCode(code: unknown): code is ApiErrorCode {
  return typeof code === 'string' && API_ERROR_CODE_SET.has(code);
}

export function toApiErrorCode(code: unknown): ApiErrorCode {
  return typeof code === 'string' && /^[A-Z][A-Z_0-9]{0,100}$/.test(code) ? (code as ApiErrorCode) : 'HOST_ERROR';
}

export interface ErrorBody {
  error: {
    code: ApiErrorCode;
    message: string;
    details?: unknown;
  };
}

export const errorBodySchema = z.object({
  error: z.object({
    code: z.enum(API_ERROR_CODES),
    message: z.string(),
    details: z.unknown().optional(),
  }),
});

