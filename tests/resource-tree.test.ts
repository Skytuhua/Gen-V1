import { afterEach, expect, it } from 'vitest';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, linkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Store } from '../packages/storage/store.ts';
import { Service } from '../packages/core/service.ts';
import { buildServer } from '../apps/server/server.ts';
import type { RuntimeAdapter, Thread, ResourceGrant } from '../packages/contracts/index.ts';
const cleanup: (() => Promise<void>)[] = [];
afterEach(async () => { for (const close of cleanup.splice(0)) await close(); });
it('lists one granted directory lazily, omits unsafe leaves and denies traversal', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'harness-tree-')); const root = join(dir, 'project'); mkdirSync(root);
  mkdirSync(join(root, 'src')); writeFileSync(join(root, 'readme.md'), 'visible'); writeFileSync(join(dir, 'private.txt'), 'private');
  linkSync(join(dir, 'private.txt'), join(root, 'alias.txt'));
  const store = new Store(join(dir, 'state'));
  const runtime: RuntimeAdapter = { configure() {}, models: async () => [], start: async () => {}, followUp: async () => {}, cancel: async () => {}, compact: async () => {}, history: async () => [], dispose: async () => {} };
  const service = new Service(store, runtime), app = await buildServer(service, { port: 4317, dev: false });
  cleanup.push(async () => { await app.close(); await service.dispose(); store.close(); rmSync(dir, { recursive: true, force: true }); });
  const thread = (await service.command({ id: 'thread-tree', type: 'thread.create', payload: {} })).result as Thread;
  const grant = (await service.command({ id: 'grant-tree', type: 'resource.grant', threadId: thread.id, payload: { path: root, kind: 'project' } })).result as ResourceGrant;
  const boot = await app.inject({ url: '/api/bootstrap', headers: { host: '127.0.0.1:4317' } });
  const headers = { host: '127.0.0.1:4317', cookie: String(boot.headers['set-cookie']).split(';')[0] };
  const tree = await app.inject({ url: `/api/resources/${grant.id}/tree`, headers });
  expect(tree.statusCode).toBe(200); expect(tree.json()).toMatchObject({ path: '', truncated: false, entries: [{ name: 'src', path: 'src', kind: 'directory' }, { name: 'readme.md', path: 'readme.md', kind: 'file' }] });
  expect(tree.body).not.toContain('private'); expect(tree.body).not.toContain('alias');
  expect((await app.inject({ url: `/api/resources/${grant.id}/tree?path=src`, headers })).json().entries).toEqual([]);
  expect((await app.inject({ url: `/api/resources/${grant.id}/tree?path=..`, headers })).statusCode).toBe(403);
  expect((await app.inject({ url: `/api/resources/${grant.id}/tree` })).statusCode).toBe(403);
}, 15_000);
